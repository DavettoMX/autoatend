const (
	jsonPath = "../assets/ui/casos_prueba.json"
	mdPath   = "../../docs/CASOS_PRUEBA.md"
	root     = "../.."
)

// annexIDs are the 29 rows of the Anexo II of the Trabajo Escrito, written out independently of
// the JSON (CP-U01 in the TE is CPU01 in the code).
var annexIDs = []string{
	"CPU01", "CPU02", "CPU03", "CPU04", "CPU05", "CPU06", "CPU07", "CPU08", "CPU09", "CPU10", "CPU11", "CPU12", "CPU13",
	"CPP01", "CPP02", "CPP03", "CPP04",
	"CPE01", "CPE02", "CPE03", "CPE04",
	"CPA01", "CPA02", "CPA03", "CPA04", "CPA05", "CPA06",
	"CPM01", "CPM02",
}

func load(t *testing.T) *casos.Matriz {
	t.Helper()
	raw, err := os.ReadFile(jsonPath)
	if err != nil {
		t.Fatal(err)
	}
	m, err := casos.Parse(raw)
	if err != nil {
		t.Fatal(err)
	}
	return m
}

// Every row of the Anexo II is in the matrix, CPU14 is the only extension, and the TE-style ID
// (CP-U01) matches the code-style ID (CPU01).
func TestCasosPrueba_TodosLosIDsDelAnexoII(t *testing.T) {
	m := load(t)
	byID := map[string]casos.Caso{}
	for _, c := range m.Casos {
		byID[c.ID] = c
	}
	for _, id := range annexIDs {
		c, ok := byID[id]
		if !ok {
			t.Errorf("Anexo II row %s is missing", id)
			continue
		}
		if c.Extension {
			t.Errorf("%s is in the Anexo II but is marked as extension", id)
		}
		if want := "CP-" + id[2:3] + id[3:]; c.IDAnexo != want {
			t.Errorf("%s: id_anexo = %q, want %q", id, c.IDAnexo, want)
		}
	}
	anexo, ext, pasan := m.Resumen()
	if anexo != len(annexIDs) || ext != 1 {
		t.Errorf("matrix has %d Anexo II rows and %d extensions, want %d and 1", anexo, ext, len(annexIDs))
	}
	if c := byID["CPU14"]; !c.Extension || c.IDAnexo != "" {
		t.Errorf("CPU14 must be the extension without id_anexo: %+v", c)
	}
	if pasan > anexo+ext {
		t.Errorf("%d cases pass out of %d", pasan, anexo+ext)
	}
}

// Two-way traceability (TE §6.3, verification A1): every listed test exists in its file, and every
// TestCP<L><NN>_* function of the repository appears in the matrix under its own ID.
func TestCasosPrueba_Trazabilidad(t *testing.T) {
	problems, err := casos.Trazabilidad(load(t), root)
	if err != nil {
		t.Fatal(err)
	}
	for _, p := range problems {
		t.Error(p)
	}
}

// The checker itself must notice both directions of drift.
func TestCasosPrueba_TrazabilidadDetectaDesvios(t *testing.T) {
	dir := t.TempDir()
	src := "package x\n\nimport \"testing\"\n\nfunc TestCPU01_Listed(t *testing.T) {}\n\nfunc TestCPU01_Orphan(t *testing.T) {}\n\nfunc TestCPU02_WrongCase(t *testing.T) {}\n\nfunc TestHelperNotACase(t *testing.T) {}\n"
	if err := os.WriteFile(filepath.Join(dir, "x_test.go"), []byte(src), 0o644); err != nil {
		t.Fatal(err)
	}
	m := &casos.Matriz{Casos: []casos.Caso{
		{ID: "CPU01", Pruebas: []casos.Prueba{
			{Funcion: "TestCPU01_Listed", Archivo: "x_test.go"},
			{Funcion: "TestCPU01_Missing", Archivo: "x_test.go"},
			{Funcion: "TestCPU01_Listed", Archivo: "other_test.go"},
		}},
		{ID: "CPU02", Pruebas: []casos.Prueba{{Funcion: "TestCPU01_Listed", Archivo: "x_test.go"}}},
	}}
	problems, err := casos.Trazabilidad(m, dir)
	if err != nil {
		t.Fatal(err)
	}
	joined := strings.Join(problems, "\n")
	for _, want := range []string{
		"TestCPU01_Missing",   // listed but not declared
		"other_test.go",       // listed in a file that does not declare it
		"TestCPU01_Orphan",    // declared but not listed
		"TestCPU02_WrongCase", // declared under CPU02 but not listed there
		"TestCPU01_Listed",    // listed under CPU02 although its name says CPU01
	} {
		if !strings.Contains(joined, want) {
			t.Errorf("the checker did not report %q; problems:\n%s", want, joined)
		}
	}
	if strings.Contains(joined, "TestHelperNotACase") {
		t.Errorf("a function that is not a case was reported:\n%s", joined)
	}
}

// docs/CASOS_PRUEBA.md is generated by make casos from the JSON and must not drift from it.
func TestCasosPrueba_MarkdownSincronizado(t *testing.T) {
	want := load(t).Markdown()
	got, err := os.ReadFile(mdPath)
	if err != nil {
		t.Fatalf("%v (run make casos)", err)
	}
	if string(got) != want {
		t.Error("docs/CASOS_PRUEBA.md differs from the JSON; run make casos")
	}
	for _, id := range annexIDs {
		if !strings.Contains(want, "**"+id+"**") {
			t.Errorf("the Markdown lacks %s", id)
		}
	}
	// A pipe inside a cell would split the column (the TE's own table suffers from this).
	if !strings.Contains(want, `\"factur(a\|as)\"`) && !strings.Contains(want, `"factur(a\|as)"`) {
		t.Error("the pipe of factur(a|as) must be escaped inside its table cell")
	}
}

func TestCasosPrueba_ParseRechazaDocumentosInvalidos(t *testing.T) {
	base := func(mutate func(s string) string) string {
		return mutate(`{"titulo":"t","nota":"n","verificado":{"fecha":"2026-10-12","comando":"make verify"},` +
			`"niveles":[{"nivel":1,"nombre":"U","seccion":"§6.3.2"}],` +
			`"casos":[{"id":"CPU01","id_anexo":"CP-U01","nivel":1,"componente":"c","tipo":"t","entrada":"e","criterio":"k",` +
			`"pruebas":[{"funcion":"TestCPU01_A","archivo":"a_test.go"}],"resultado":"r","estado":"pasa"}]}`)
	}
	if _, err := casos.Parse([]byte(base(func(s string) string { return s }))); err != nil {
		t.Fatalf("the valid document was rejected: %v", err)
	}
	for name, mutate := range map[string]func(string) string{
		"unknown field": func(s string) string { return strings.Replace(s, `"nota"`, `"nota_x"`, 1) },
		"undefined level": func(s string) string {
			return strings.Replace(s, `"nivel":1,"componente"`, `"nivel":9,"componente"`, 1)
		},
		"bad estado": func(s string) string { return strings.Replace(s, `"pasa"`, `"quiza"`, 1) },
		"no tests": func(s string) string {
			return strings.Replace(s, `[{"funcion":"TestCPU01_A","archivo":"a_test.go"}]`, `[]`, 1)
		},
		"no id_anexo":   func(s string) string { return strings.Replace(s, `"id_anexo":"CP-U01"`, `"id_anexo":""`, 1) },
		"missing fecha": func(s string) string { return strings.Replace(s, `"fecha":"2026-10-12"`, `"fecha":""`, 1) },
		"commit field": func(s string) string {
			return strings.Replace(s, `"comando":"make verify"`, `"comando":"make verify","commit":"abc"`, 1)
		},
		"duplicate id": func(s string) string {
			return strings.Replace(s, `"resultado":"r","estado":"pasa"}]`, `"resultado":"r","estado":"pasa"},{"id":"CPU01"}]`, 1)
		},
		"not json": func(s string) string { return "{" },
	} {
		if _, err := casos.Parse([]byte(base(mutate))); err == nil {
			t.Errorf("%s: Parse accepted an invalid document", name)
		}
	}
}

// Commit hashes differ between the local repository and the GitHub export, so the matrix never
// records one; the date is rendered in Spanish.
func TestCasosPrueba_SinCommitYFechaEnEspanol(t *testing.T) {
	raw, err := os.ReadFile(jsonPath)
	if err != nil {
		t.Fatal(err)
	}
	if strings.Contains(string(raw), `"commit"`) {
		t.Error("casos_prueba.json records a commit hash")
	}
	md, err := os.ReadFile(mdPath)
	if err != nil {
		t.Fatal(err)
	}
	if strings.Contains(strings.ToLower(string(md)), "commit") {
		t.Error("docs/CASOS_PRUEBA.md mentions a commit")
	}
	if !strings.Contains(string(md), "- Verificación: `make verify`, 12 de octubre de 2026.") {
		t.Error("docs/CASOS_PRUEBA.md lacks the verification line with the Spanish date")
	}
	for iso, want := range map[string]string{
		"2026-10-12": "12 de octubre de 2026",
		"2026-01-01": "1 de enero de 2026",
		"2027-12-31": "31 de diciembre de 2027",
		"no-fecha":   "no-fecha",
	} {
		if got := casos.FechaES(iso); got != want {
			t.Errorf("FechaES(%q) = %q, want %q", iso, got, want)
		}
	}
}
